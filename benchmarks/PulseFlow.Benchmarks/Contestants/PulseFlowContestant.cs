using System.Runtime.CompilerServices;
using Microsoft.Extensions.DependencyInjection;
using PulseFlow.Application;
using PulseFlow.Application.Commands;
using PulseFlow.Application.Mediator;
using PulseFlow.Application.Queries;

namespace PulseFlow.Benchmarks.PulseFlowSide;

public sealed record Ping(int Value) : ICommand<int>;

public sealed class PingHandler : ICommandHandler<Ping, int>
{
    public ValueTask<Result<int>> Handle(Ping command, CancellationToken cancellationToken)
        => ValueTask.FromResult(Result<int>.Ok(command.Value));
}

public sealed record Pinged(int Value) : INotification;

public sealed class PingedHandlerA : INotificationHandler<Pinged>
{
    public ValueTask Handle(Pinged notification, CancellationToken cancellationToken) => ValueTask.CompletedTask;
}

public sealed class PingedHandlerB : INotificationHandler<Pinged>
{
    public ValueTask Handle(Pinged notification, CancellationToken cancellationToken) => ValueTask.CompletedTask;
}

public sealed record CountTo(int Count) : IStreamQuery<int>;

public sealed class CountToHandler : IStreamQueryHandler<CountTo, int>
{
    public async IAsyncEnumerable<int> Handle(CountTo query, [EnumeratorCancellation] CancellationToken cancellationToken)
    {
        for (var i = 0; i < query.Count; i++)
            yield return i;
    }
}

public sealed class PassThroughA<TRequest, TResponse> : IPipelineBehavior<TRequest, TResponse>
{
    public ValueTask<TResponse> Handle(TRequest request, RequestHandlerDelegate<TResponse> next, CancellationToken cancellationToken)
        => next();
}

public sealed class PassThroughB<TRequest, TResponse> : IPipelineBehavior<TRequest, TResponse>
{
    public ValueTask<TResponse> Handle(TRequest request, RequestHandlerDelegate<TResponse> next, CancellationToken cancellationToken)
        => next();
}

public static class PulseFlowSetup
{
    /// <param name="singleton">
    /// false: PulseFlow defaults (scoped mediator, transient handlers and behaviors).
    /// true: singleton mediator, handlers and behaviors, the configuration Mediator uses by default.
    /// </param>
    public static ServiceProvider Build(bool withBehaviors, bool singleton)
    {
        var services = new ServiceCollection();

        // Called on the static class to avoid any ambiguity with the AddMediator generated by Mediator.
        global::PulseFlow.Application.Mediator.ServiceCollectionExtensions.AddMediator(services, options =>
        {
            if (!singleton)
                return;
            options.HandlerLifetime = ServiceLifetime.Singleton;
            options.MediatorLifetime = ServiceLifetime.Singleton;
        }, typeof(PulseFlowSetup).Assembly);

        if (withBehaviors)
        {
            var lifetime = singleton ? ServiceLifetime.Singleton : ServiceLifetime.Transient;
            services.AddPipelineBehavior(typeof(PassThroughA<,>), lifetime);
            services.AddPipelineBehavior(typeof(PassThroughB<,>), lifetime);
        }

        return services.BuildServiceProvider();
    }
}
